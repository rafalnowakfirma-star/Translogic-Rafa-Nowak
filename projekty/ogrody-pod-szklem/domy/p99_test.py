"""Test: patio sezonowe, taras na piętrze, schody proste i kręcone, dach fold."""
from silnik import House, rect

H = House("p99", "Test", "Test silnika", style=dict(fasada="drewno", dach="zwir"))
H.level(0, z=0.0, h=3.4)
H.level(1, z=3.4, h=3.4)
H.ogrod("og", "Ogród", rect(5, 5, 13, 11), roof_type="fold", style="tropikalny", seed=2)
H.room("hol", "Hol", "hol", rect(0, 0, 5, 5))
H.room("bib", "Biblioteka", "biblioteka", rect(5, 0, 13, 5), ext="slits")
H.room("biu", "Biuro", "biuro", rect(13, 0, 18, 11), ext={"E": "glass"}, garden="glass")
H.room("sal", "Salon z kuchnią", "salon_kuchnia", rect(5, 11, 18, 16), levels=2, ext={"S": "glass_slide"}, kitchen_at="E")
H.room("ps", "Patio sezonowe", "patio_sezonowe", rect(0, 11, 5, 16))
H.room("syp", "Sypialnia", "sypialnia_glowna", rect(0, 5, 5, 11), ext={"W": "glass_slide"})
H.stair("straight", level=0, rect=(0.4, 0.5, 4.6, 1.6), up="E")
H.room("gos", "Pokój gościnny", "gosc", rect(0, 0, 5, 5), level=1)
H.room("tar", "Taras", "taras", rect(5, 0, 13, 5), level=1)
H.room("syp2", "Sypialnia", "sypialnia", rect(0, 5, 5, 11), level=1)
H.connect("hol", "bib", "wide")
H.connect("bib", "biu", "double")
H.connect("biu", "sal", "wide")
H.connect("sal", "ps", "slide")
H.connect("hol", "syp", "door")
H.connect("gos", "tar", "slide")
H.connect("gos", "syp2", "door")
H.entrance("hol", "N")
H.cut("A–A", (2.5, -2), (2.5, 18))
H.cut("B–B", (-2, 13.5), (20, 13.5))
